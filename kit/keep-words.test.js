function breaks(text){
  // 可換行的位置：兩個單位之間；沒被包起來的文字裡，每個字之間
  const set = new Set();
  let pos = 0;
  for(const u of kwTokens(text, seg)){
    if(u.keep){ pos += u.s.length; set.add(pos); }
    else for(const ch of u.s){ pos += ch.length; set.add(pos); }
  }
  return set;
}
// 英數、小數點、百分比相鄰時瀏覽器本來就不會換行，不算被拆開
const glue = (a, b)=> /[A-Za-z0-9.%]/.test(a) && /[A-Za-z0-9.%]/.test(b);

let pass = 0, fail = 0;
for(const [text, must, mustBreak] of CASES){
  const bk = breaks(text);
  const bad = [];
  for(const m of must){
    const i = text.indexOf(m);
    if(i < 0){ bad.push(m + '（句子裡沒有這個詞，案例寫錯）'); continue; }
    for(let q = i + 1; q < i + m.length; q++) if(bk.has(q) && !glue(text[q - 1], text[q])){ bad.push(m); break; }
  }
  for(const mb of (mustBreak || [])){
    const [a, b] = mb.split('|');
    const i = text.indexOf(a + b);
    if(i < 0){ bad.push(mb + '（案例寫錯）'); continue; }
    if(!bk.has(i + a.length)) bad.push('「' + a + '」和「' + b + '」之間應該可以換行');
  }
  if(bad.length){ fail++; console.log('失敗：' + kwTokens(text, seg).map(u=> u.s).join('｜') + '\n      ' + bad.join('、')); }
  else pass++;
}
console.log(`通過 ${pass}，失敗 ${fail}（共 ${CASES.length} 句）`);
if(fail) process.exit(1);
console.log('全部通過');
